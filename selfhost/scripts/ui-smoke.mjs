// Drives the built app in headless Chromium: register, build a roadmap in the
// editor, upload a screenshot, publish, read it back, tick progress.
// Usage: node scripts/ui-smoke.mjs http://127.0.0.1:8090 [screenshot-dir]
import { chromium } from 'playwright'
import fs from 'node:fs'

const base = process.argv[2] || 'http://127.0.0.1:8090'
const shots = process.argv[3] || ''
const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width: 1400, height: 900 } })
const errors = []
page.on('pageerror', e => errors.push('pageerror: ' + e.message))
page.on('console', m => { if (m.type() === 'error') errors.push('console: ' + m.text()) })
const shot = async (name) => { if (shots) await page.screenshot({ path: `${shots}/${name}.png`, fullPage: false }) }
const step = (s) => console.log('•', s)

step('register first user')
await page.goto(base + '/register')
await page.fill('input[type=text]', 'Vijay')
await page.fill('input[type=email]', 'vijay@example.com')
await page.fill('input[type=password]', 'password123')
await page.click('button:has-text("Create account")')
await page.waitForURL('**/me')

step('create roadmap')
await page.click('button:has-text("New roadmap")')
await page.fill('.newbox input', 'Class 9 CBSE Maths')
await page.click('.newbox button:has-text("Create")')
await page.waitForURL('**/edit/**')

step('load sample, then add a topic and a subtopic')
await page.click('summary:has-text("More")')
await page.click('button:has-text("Load sample")')
await page.click('button.addbtn:has-text("+ topic")')
await page.fill('.bld-inspector input[type=text]', 'Number systems')
const topics = page.locator('.o-topic')
await topics.last().locator('button:has-text("+ subtopic")').click()
await page.fill('.bld-inspector input[type=text]', 'Rational numbers')
await page.locator('.bld-inspector .rte-area').first().fill('Numbers of the form **p/q**.')
await page.click('button:has-text("+ link")')
await page.fill('.linkrow input:nth-child(1)', 'Khan Academy')
await page.fill('.linkrow input:nth-child(2)', 'khanacademy.org/math')

step('upload a screenshot through the file picker')
const png = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mNgYGD4DwABBAEAX+XJ4QAAAABJRU5ErkJggg==', 'base64')
const [chooser] = await Promise.all([page.waitForEvent('filechooser'), page.click('button:has-text("+ screenshot")')])
await chooser.setFiles({ name: 'shot.png', mimeType: 'image/png', buffer: png })
await page.waitForSelector('.imgrow img')
const src = await page.getAttribute('.imgrow img', 'src')
if (!src.startsWith('/img/')) throw new Error('image not uploaded: ' + src)

step('save with Ctrl+S and publish')
await page.keyboard.press('Control+s')
await page.waitForSelector('.bld-save:has-text("saved")')
await shot('01-builder')
await page.click('button:has-text("Publish")')
await page.waitForSelector('.st-published')

step('preview clicking a node opens the drawer')
await page.click('.bld-preview .rm-node:has-text("Rational numbers")')
await page.waitForSelector('.rm-drawer h2:has-text("Rational numbers")')
const desc = await page.textContent('.rm-drawer .rm-d-desc')
if (!desc.includes('p/q')) throw new Error('desc not rendered')
const linkHref = await page.getAttribute('.rm-d-links a', 'href')
if (!linkHref.startsWith('https://khanacademy.org')) throw new Error('link not normalised: ' + linkHref)

step('reader page: progress, checklist, deep link')
await page.goto(base + '/')
await page.waitForSelector('.card h3:has-text("Class 9 CBSE Maths")')
await shot('02-home')
await page.click('.card:has-text("Class 9 CBSE Maths")')
await page.waitForSelector('.rm-node')
await page.click('.rm-node:has-text("Rational numbers")')
await page.click('.rm-d-status button:has-text("Done")')
await page.waitForSelector('.rm-count:has-text("1 of")')
await shot('03-reader')
const nodeId = await page.getAttribute('.rm-node:has-text("Rational numbers")', 'data-id')
await page.click('.rm-vbtn')
if (!(await page.isChecked(`.rm-l-row[data-id="${nodeId}"] input`))) throw new Error('checklist not in sync')
await page.reload()
await page.waitForSelector('.rm-count:has-text("1 of")')
step('progress survived reload (server-side)')
await page.goto(base + `/r/class-9-cbse-maths#${nodeId}`)
await page.waitForSelector('.rm-drawer h2:has-text("Rational numbers")')

step('sign out; anonymous reader keeps progress in localStorage')
await page.click('button:has-text("Sign out")')
await page.goto(base + '/r/class-9-cbse-maths')
await page.waitForSelector('.rm-node')
await page.click('.rm-node:has-text("Number systems")')
await page.click('.rm-d-status button:has-text("In progress")')
await page.reload()
await page.waitForSelector('.rm-node.rm-prog')

step('member signs up, submits for review; admin sees queue')
await page.goto(base + '/register')
await page.fill('input[type=text]', 'Student')
await page.fill('input[type=email]', 'student@example.com')
await page.fill('input[type=password]', 'password123')
await page.click('button:has-text("Create account")')
await page.waitForURL('**/me')
await page.click('button:has-text("New roadmap")')
await page.fill('.newbox input', 'Intro to Python')
await page.click('.newbox button:has-text("Create")')
await page.waitForURL('**/edit/**')
await page.click('button.addbtn:has-text("+ topic")')
await page.fill('.bld-inspector input[type=text]', 'Install Python')
await page.click('button:has-text("Submit for review")')
await page.waitForSelector('.st-review')
await page.click('button:has-text("Sign out")')
await page.goto(base + '/login')
await page.fill('input[type=email]', 'vijay@example.com')
await page.fill('input[type=password]', 'password123')
await page.click('button:has-text("Sign in")')
await page.waitForURL('**/me')
await page.goto(base + '/admin')
await page.waitForSelector('.tbl a:has-text("Intro to Python")')
await shot('04-admin')
await page.click('.tbl button:has-text("Publish")')
await page.waitForSelector('.hint:has-text("Nothing waiting")')

if (errors.length) { console.log('BROWSER ERRORS:\n' + errors.join('\n')); process.exit(1) }
console.log('UI SMOKE OK')
await browser.close()
